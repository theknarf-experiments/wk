#!/usr/bin/env bash
# Build a real SoundFont synthesizer into a wk MIDI node: FluidLite
# (divideconcept/FluidLite — the FluidSynth synthesis engine as a
# dependency-free library, pinned to a commit) plus our thin pump in
# fluidsynth_wk.c. MIDI comes in through the shared ../midi-compat shim
# (wk:midi) and PCM goes out through the shared ../audio-compat shim
# (wk:webaudio's pcm-queue).
#
# Why not FluidSynth proper: its CMakeLists hard-requires glib + gthread
# ("Mandatory libraries") and pthreads, none of which exist on wasi — the
# probe (cmake with every feature off against the wasi-sdk toolchain) dies at
# find_package(Threads REQUIRED) before even reaching the glib check.
# FluidLite is the established glib-free fork of the same engine and is
# API-compatible for everything this node does. No setjmp anywhere in its
# sources (verified: grep -r setjmp finds nothing), so no sjlj flags.
#
# Also fetches TimGM6mb.sf2 (Tim Brechbill's 6 MB General MIDI soundfont,
# GPLv2 — pulled pinned from the Debian pool, where its license is vetted) so
# the Dockerfile can ship a playable image out of the box. Sources and the
# soundfont are fetched at build and gitignored, like doom's.
#
# Requires wasi-sdk (set WASI_SDK; defaults to the mise-pinned install),
# wasm-tools, wit-bindgen, curl.
set -euo pipefail
cd "$(dirname "$0")"

# Default to the mise-pinned toolchain when present; ~/wasi-sdk may be stale.
MISE_SDK="$HOME/.local/share/mise/installs/github-web-assembly-wasi-sdk/wasi-sdk-34-rc.2"
WASI_SDK="${WASI_SDK:-$([ -d "$MISE_SDK" ] && echo "$MISE_SDK" || echo "$HOME/wasi-sdk")}"
# Same guard as bash/pipe-compat: the other C plugins are built and tested
# against exactly this SDK, and a silent mismatch wastes an afternoon.
EXPECT="wasi-sdk-34-rc.2"
case "$WASI_SDK" in
    *"$EXPECT"*) ;;
    *)
        echo "fluidsynth: expected $EXPECT (set WASI_SDK), got: $WASI_SDK" >&2
        exit 1
        ;;
esac
CLANG="$WASI_SDK/bin/clang"

# FluidLite, pinned. LGPL-2.1 — fetched at build like doom's engine sources,
# not vendored into this repo.
FL_COMMIT=4a01cf1c67419e71da971d209f2855bbf4f3bab8
FL_DIR="FluidLite-$FL_COMMIT"
if [ ! -d "$FL_DIR" ]; then
    echo "fetching FluidLite @ ${FL_COMMIT:0:12}..."
    curl -fsSL "https://github.com/divideconcept/FluidLite/archive/$FL_COMMIT.tar.gz" | tar xz
fi

# TimGM6mb.sf2: a small (~6 MB) free General MIDI soundfont, GPLv2, pinned via
# the Debian source package (timgm6mb-soundfont 1.3). Kept beside the wasm for
# the Dockerfile's COPY.
if [ ! -f soundfont.sf2 ]; then
    echo "fetching TimGM6mb.sf2 (timgm6mb-soundfont 1.3, Debian pool)..."
    curl -fsSL "http://deb.debian.org/debian/pool/main/t/timgm6mb-soundfont/timgm6mb-soundfont_1.3.orig.tar.gz" \
        | tar xz --strip-components=1 "timgm6mb-soundfont_1.3/TimGM6mb.sf2"
    mv TimGM6mb.sf2 soundfont.sf2
fi

# FluidLite's cmake would generate fluid_config.h; ours is a static transcript
# of its defaults (WITH_FLOAT, SF3 off — SF3 would drag in a vorbis decoder)
# for the one target this build has.
mkdir -p gen
cat > gen/fluid_config.h <<'EOF'
/* Generated by build.sh — FluidLite's cmake fluid_config.h for wasm32-wasi:
 * the cmake defaults (WITH_FLOAT on, SF3 off), C99 headers all present. */
#define DEBUG 0
#define VERSION "1.2.2"
#define SF3_DISABLED 0
#define SF3_XIPH_VORBIS 1
#define SF3_STB_VORBIS 2
#define SF3_SUPPORT SF3_DISABLED
#define WITH_FLOAT
#define HAVE_STRING_H 1
#define HAVE_STDLIB_H 1
#define HAVE_STDIO_H 1
#define HAVE_STDARG_H 1
#define HAVE_MATH_H 1
#define HAVE_LIMITS_H 1
#define HAVE_FCNTL_H 1
EOF

# Shared MIDI shim + its wk:midi bindings (regenerated each build) — the
# input port fluidsynth_wk.c drains.
MIDICOMPAT="$(pwd)/../midi-compat"
MIDIGEN="$MIDICOMPAT/gen"
mkdir -p "$MIDIGEN"
wit-bindgen c --world wkmidi "$MIDICOMPAT/wit" --out-dir "$MIDIGEN"

# Shared audio shim + its wk:webaudio bindings (regenerated each build) — the
# pcm-queue the rendered stereo blocks go to.
AUDIOCOMPAT="$(pwd)/../audio-compat"
AUDIOGEN="$AUDIOCOMPAT/gen"
mkdir -p "$AUDIOGEN"
wit-bindgen c --world wkaudio "$AUDIOCOMPAT/wit" --out-dir "$AUDIOGEN"

# WASIp1→component adapter, pinned to our wasmtime (46); fetched and cached if
# a registry copy isn't present (same dance as doom's build).
WASMTIME_VER=46.0.1
ADAPTER="${WASI_ADAPTER:-$(find "$HOME/.cargo/registry/src" -name 'wasi_snapshot_preview1.command.wasm' 2>/dev/null | head -1)}"
if [ -z "$ADAPTER" ] || [ ! -f "$ADAPTER" ]; then
    ADAPTER="$MIDIGEN/wasi_snapshot_preview1.command.wasm"
    if [ ! -f "$ADAPTER" ]; then
        echo "fetching WASI command adapter $WASMTIME_VER..."
        curl -fsSL "https://github.com/bytecodealliance/wasmtime/releases/download/v$WASMTIME_VER/wasi_snapshot_preview1.command.wasm" -o "$ADAPTER"
    fi
fi

# The engine: FluidLite's cmake SOURCES list (fluid_dsp_float.c is #included
# by fluid_voice.c and must not be compiled separately — it isn't in the list).
FL_SRCS=(
    fluid_init.c fluid_chan.c fluid_chorus.c fluid_conv.c fluid_defsfont.c
    fluid_dsp_float.c fluid_gen.c fluid_hash.c fluid_list.c fluid_mod.c
    fluid_ramsfont.c fluid_rev.c fluid_settings.c fluid_synth.c fluid_sys.c
    fluid_tuning.c fluid_voice.c
)
SRCS=()
for s in "${FL_SRCS[@]}"; do SRCS+=("$FL_DIR/src/$s"); done

# -I$FL_DIR/src/watcom supplies fluidlite/version.h (the pregenerated copy of
# what cmake templates; same version, 1.2.2).
"$CLANG" --target=wasm32-wasip1 -O2 \
    -Igen -I"$FL_DIR/include" -I"$FL_DIR/src" -I"$FL_DIR/src/watcom" \
    -I"$MIDICOMPAT" -I"$MIDIGEN" -I"$AUDIOCOMPAT" -I"$AUDIOGEN" \
    "${SRCS[@]}" fluidsynth_wk.c \
    "$MIDICOMPAT/wkmidi.c" "$MIDIGEN/wkmidi.c" "$MIDIGEN/wkmidi_component_type.o" \
    "$AUDIOCOMPAT/wkaudio.c" "$AUDIOGEN/wkaudio.c" "$AUDIOGEN/wkaudio_component_type.o" \
    -o fluidsynth.core.wasm

wasm-tools component new fluidsynth.core.wasm --adapt "wasi_snapshot_preview1=$ADAPTER" -o fluidsynth.wasm
rm -f fluidsynth.core.wasm
echo "built plugins/fluidsynth/fluidsynth.wasm"
